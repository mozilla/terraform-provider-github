//go:build ignore

package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"maps"
	"net/http"
	"os"
	"slices"
	"strings"
	"time"
)

const sourceURL = "https://raw.githubusercontent.com/github/docs/5baaf9699698ed5f935ebc84ea2693a88ab6d8f7/src/github-apps/data/ghec-2026-03-10/server-to-server-permissions.json"

func main() {
	client := &http.Client{Timeout: 30 * time.Second}
	response, err := client.Get(sourceURL)
	if err != nil {
		log.Fatalf("download GitHub App permission catalog: %v", err)
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		log.Fatalf("download GitHub App permission catalog: %s", response.Status)
	}

	var catalog map[string]struct {
		DisplayTitle string `json:"displayTitle"`
	}
	if err := json.NewDecoder(response.Body).Decode(&catalog); err != nil {
		log.Fatalf("decode GitHub App permission catalog: %v", err)
	}
	if len(catalog) == 0 {
		log.Fatal("GitHub App permission catalog is empty")
	}

	var source bytes.Buffer
	source.WriteString("// Code generated by go generate. DO NOT EDIT.\n\n")
	source.WriteString("package githubapppermissions\n\n")
	source.WriteString("// permissionScopes uses the leading scope from each entry's displayTitle.\n")
	fmt.Fprintf(&source, "// %s\n", sourceURL)
	source.WriteString("var permissionScopes = map[string]Scope{\n")
	for _, permission := range slices.Sorted(maps.Keys(catalog)) {
		title := catalog[permission].DisplayTitle
		scope, _, found := strings.Cut(title, " permissions for ")
		if !found {
			log.Fatalf("unexpected display title for permission %q: %q", permission, title)
		}
		switch scope {
		case "Enterprise", "Organization", "Repository", "User":
			fmt.Fprintf(&source, "\t%q: %s,\n", permission, scope)
		default:
			log.Fatalf("unexpected scope for permission %q: %q", permission, scope)
		}
	}
	source.WriteString("}\n")

	formatted, err := format.Source(source.Bytes())
	if err != nil {
		log.Fatalf("format permission scope table: %v", err)
	}
	if err := os.WriteFile("scopes_generated.go", formatted, 0o644); err != nil {
		log.Fatalf("write permission scope table: %v", err)
	}
}
